import { writeFile, mkdir } from "node:fs/promises";
import { createHash } from "node:crypto";
import { GLTFExporter } from "three/addons/exporters/GLTFExporter.js";
import { createDomModel } from "./dom-model.mjs";

// GLTFExporter uses this browser API for binary blobs; no DOM or image input is needed.
globalThis.FileReader ??= class FileReader {
  readAsArrayBuffer(blob) {
    blob.arrayBuffer().then((result) => {
      this.result = result;
      this.onloadend?.();
    });
  }
};
const { root, animations } = createDomModel();
const data = await new GLTFExporter().parseAsync(root, {
  binary: true,
  animations,
  trs: true,
  copyright:
    "Dom’s Plumbing Services — custom character based on the supplied reference.",
});
await mkdir(new URL("../public/models/", import.meta.url), { recursive: true });
await writeFile(
  new URL("../public/models/dom.glb", import.meta.url),
  Buffer.from(data),
);
// A new export also reloads mounted characters during local development.
await writeFile(
  new URL("../src/lib/dom-model-version.ts", import.meta.url),
  `// Generated by scripts/build-dom-model.mjs.\nexport const domModelVersion = "${createHash("sha256").update(Buffer.from(data)).digest("hex").slice(0, 12)}";\n`,
);
let meshes = 0;
root.traverse((object) => {
  if (object.isMesh) meshes++;
});
console.log(
  `Exported Dom: ${meshes} mesh parts, ${animations.length} animation clips, ${(data.byteLength / 1024).toFixed(0)} KB.`,
);
